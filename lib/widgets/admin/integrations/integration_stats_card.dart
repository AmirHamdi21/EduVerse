                      style: TextStyle(color: Colors.white70, fontSize: 12),
                    ),
                  ],
                ),
              ),
            ],
          ),
          const SizedBox(height: 20),
          Row(
            children: [
              _buildStatItem('Active', '12', Icons.check_circle_rounded),
              const SizedBox(width: 16),
              _buildStatItem('Inactive', '3', Icons.pause_circle_rounded),
              const SizedBox(width: 16),
              _buildStatItem('Error', '1', Icons.error_rounded),
